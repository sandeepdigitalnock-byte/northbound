export const ll = (lat, lon, r = 1) => {
  const phi = (90 - lat) * Math.PI / 180, th = (lon + 180) * Math.PI / 180
  return new THREE.Vector3(-r * Math.sin(phi) * Math.cos(th), r * Math.cos(phi), r * Math.sin(phi) * Math.sin(th))
}
export function arc(a, b, lift = 0.4, seg = 90) {
  const A = ll(a[0], a[1]), B = ll(b[0], b[1])
  const mid = A.clone().add(B).multiplyScalar(0.5).normalize().multiplyScalar(1 + lift * A.distanceTo(B))
  return new THREE.QuadraticBezierCurve3(A, mid, B).getPoints(seg)
}

